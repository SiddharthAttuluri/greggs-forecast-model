"""Write the saved simulation outputs into the 'Simulation' tab of the Excel model.

Everything on that tab is a saved value from the last run of monte_carlo.py, not a live formula.
The Summary tab links to the cells written here (fixed positions), and the Checks tab flags the
tab as out of date when the live base case no longer matches the base case it was run on.

Refresh after changing any assumption (Scenarios!B4 must be set to Base and the workbook saved):
    python simulation/monte_carlo.py --workbook model/GRG_model_v1.0.xlsx
    python simulation/charts.py
    python simulation/add_to_workbook.py --src model/GRG_model_v1.0.xlsx --out model/GRG_model_v1.0.xlsx
then open the workbook in Excel and let it recalculate (or run LibreOffice recalc), and check the Checks tab.
"""
import argparse
import csv
import datetime
import pathlib

from openpyxl import load_workbook
from openpyxl.drawing.image import Image
from openpyxl.styles import Alignment, Font, PatternFill

ROOT = pathlib.Path(__file__).resolve().parents[1]
RES = ROOT / "simulation" / "results"
F = "Arial"
TITLE = Font(name=F, bold=True, size=14, color="1F3864"); BOLD = Font(name=F, bold=True, size=10)
BLACK = Font(name=F, size=10); SUB = Font(name=F, italic=True, size=9, color="595959")
HDR = Font(name=F, bold=True, color="FFFFFF", size=10); HDRFILL = PatternFill("solid", fgColor="1F3864")
WRAP = Alignment(wrap_text=True, vertical="top")

# fixed layout: the Summary and Checks tabs link to these rows
ROW_PCT, ROW_PROB, ROW_TORN, ROW_SCEN, ROW_SENS, ROW_CONC = 5, 23, 31, 44, 50, 57

DEFAULT_CONCLUSIONS = [
    "On the chosen ranges and correlations, FY26 underlying profit beats FY25's £171.9m in about 90% of 10,000 runs "
    "(P5–P95: £170m–£190m). That makes growth the most likely outcome under these inputs, not a certainty: the "
    "probability depends on the ranges set, and a shock outside them is not captured.",
    "Cash stays positive in every simulated run and falls below £50m in about 1% of runs. On these assumptions, falling capex "
    "lets Greggs fund openings, restructuring and dividends without new debt, after negative free cash flow in FY25.",
    "I would watch like-for-like growth. Margin moves FY28 profit most (a £53m swing across its range), but LFL moves "
    "it £23m directly and, through its 0.5 correlation with margin in the simulation, pulls margin with it. LFL has "
    "slowed from 17.8% in FY22 to 2.4% in FY25.",
]


def header(ws, r, cols):
    for i, h in enumerate(cols):
        if h is None:
            continue
        c = ws.cell(row=r, column=1 + i, value=h); c.font = HDR; c.fill = HDRFILL
        c.alignment = Alignment(horizontal="left" if i == 0 else "right")


def rows_of(name):
    with open(RES / name, newline="") as f:
        return list(csv.reader(f))[1:]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(ROOT / "model" / "GRG_model_v1.0.xlsx"))
    ap.add_argument("--out", default=str(ROOT / "model" / "GRG_model_v1.0.xlsx"))
    a = ap.parse_args()
    wb = load_workbook(a.src)

    conclusions = DEFAULT_CONCLUSIONS
    position = len(wb.sheetnames)
    if "Simulation" in wb.sheetnames:
        old = wb["Simulation"]
        kept = [old.cell(row=ROW_CONC + 1 + k, column=2).value for k in range(3)]
        if all(isinstance(t, str) and t.strip() for t in kept):
            conclusions = kept
        position = wb.sheetnames.index("Simulation")
        del wb["Simulation"]
    elif "Checks" in wb.sheetnames:
        position = wb.sheetnames.index("Checks")
    ws = wb.create_sheet("Simulation", position)

    ws["A1"] = "Monte Carlo simulation – 10,000 runs of the full three-statement model"; ws["A1"].font = TITLE
    ws["A2"] = ("Saved values, not live formulas: generated by simulation/monte_carlo.py (seed 42) from the base case and "
                "the min / max ranges on the Drivers tab. Results are conditional on those ranges and correlations. "
                "After changing an assumption, set Scenarios!B4 to Base and re-run: monte_carlo.py, charts.py, then "
                "add_to_workbook.py (instructions in the README and on the Notes tab). The Checks tab flags this tab "
                "if it no longer matches the live base case.")
    ws["A2"].font = SUB; ws["A2"].alignment = WRAP
    ws.merge_cells("A2:I2"); ws.row_dimensions[2].height = 52
    ws["A3"] = f"Last run: {datetime.date.today():%d %b %Y} · 10,000 runs · seed 42"
    ws["A3"].font = SUB

    r = ROW_PCT - 1
    ws.cell(row=r, column=1, value="Percentiles (£m)").font = BOLD
    header(ws, ROW_PCT, ["Measure", "Year", "P5", "P25", "Median", "P75", "P95", "Mean", "Base case at run"])
    r = ROW_PCT
    for row in rows_of("summary_percentiles.csv"):
        r += 1
        for i, v in enumerate(row):
            c = ws.cell(row=r, column=1 + i, value=float(v) if i >= 2 else v); c.font = BLACK
            if i >= 2:
                c.number_format = "#,##0.0"

    ws.cell(row=ROW_PROB - 1, column=1, value="Probabilities (conditional on the ranges and correlations used)").font = BOLD
    header(ws, ROW_PROB, ["Question", None, None, None, None, None, "Probability"])
    r = ROW_PROB
    for q, p in rows_of("probabilities.csv"):
        r += 1
        ws.cell(row=r, column=1, value=q).font = BLACK
        c = ws.cell(row=r, column=7, value=float(p)); c.font = BLACK; c.number_format = "0.0%"

    ws.cell(row=ROW_TORN - 1, column=1,
            value="Tornado: FY28 underlying PBT with one driver at its min / max (others at base)").font = BOLD
    header(ws, ROW_TORN, ["Driver", None, None, "At min", "At max", "Swing", "Lowest cash at min", "Lowest cash at max"])
    r = ROW_TORN
    for row in rows_of("tornado_fy28_upbt.csv"):
        r += 1
        ws.cell(row=r, column=1, value=row[0]).font = BLACK
        for i, v in enumerate(row[1:]):
            c = ws.cell(row=r, column=4 + i, value=float(v)); c.font = BLACK; c.number_format = "#,##0.0"

    ws.cell(row=ROW_SCEN - 1, column=1,
            value="Scenario snapshot (£m): the five scenario drivers at their range min / max together").font = BOLD
    header(ws, ROW_SCEN, ["Scenario", "Rev FY26", "Rev FY27", "Rev FY28", "uPBT FY26", "uPBT FY27", "uPBT FY28",
                          "Lowest cash"])
    r = ROW_SCEN
    for row in rows_of("scenarios.csv"):
        r += 1
        ws.cell(row=r, column=1, value=row[0]).font = BLACK
        for i, v in enumerate(row[1:]):
            c = ws.cell(row=r, column=2 + i, value=float(v)); c.font = BLACK; c.number_format = "#,##0.0"

    ws.cell(row=ROW_SENS - 1, column=1,
            value="Sensitivities: change in underlying PBT (£m) from ±1 point in every year, others at base").font = BOLD
    header(ws, ROW_SENS, ["Change", "FY26", "FY27", "FY28"])
    r = ROW_SENS
    for row in rows_of("sensitivities_upbt.csv"):
        r += 1
        ws.cell(row=r, column=1, value=row[0].replace("-1", "−1")).font = BLACK
        for i, v in enumerate(row[1:]):
            c = ws.cell(row=r, column=2 + i, value=float(v)); c.font = BLACK; c.number_format = "+#,##0.0;−#,##0.0"

    ws.cell(row=ROW_CONC, column=1, value="Conclusions (conditional on the inputs above)").font = BOLD
    for k, text in enumerate(conclusions):
        rr = ROW_CONC + 1 + k
        ws.cell(row=rr, column=1, value=f"{k + 1}.").font = BLACK
        c = ws.cell(row=rr, column=2, value=text); c.font = BLACK; c.alignment = WRAP
        ws.merge_cells(start_row=rr, start_column=2, end_row=rr, end_column=9)
        ws.row_dimensions[rr].height = 46
        ws.cell(row=rr, column=1).alignment = Alignment(vertical="top")

    ws.column_dimensions["A"].width = 58
    for col in "BCDEFGHI":
        ws.column_dimensions[col].width = 12
    img1 = Image(str(RES / "fy26_upbt_histogram.png")); img1.width, img1.height = 640, 336
    img2 = Image(str(RES / "tornado_fy28_upbt.png")); img2.width, img2.height = 640, 304
    ws.add_image(img1, "K4"); ws.add_image(img2, "K23")
    ws.sheet_view.showGridLines = False
    wb.save(a.out)
    print("saved", a.out)


if __name__ == "__main__":
    main()

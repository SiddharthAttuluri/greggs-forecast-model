"""Write the Monte Carlo results into a 'Simulation' tab of the Excel model.

Usage:
    python simulation/add_to_workbook.py --src model/GRG_model_v0.5.xlsx --out model/GRG_model_v0.6.xlsx
"""
import argparse
import csv
import pathlib

from openpyxl import load_workbook
from openpyxl.drawing.image import Image
from openpyxl.styles import Font, PatternFill

ROOT = pathlib.Path(__file__).resolve().parents[1]
RES = ROOT / "simulation" / "results"
F = "Arial"
TITLE = Font(name=F, bold=True, size=14); BOLD = Font(name=F, bold=True, size=10)
BLACK = Font(name=F, size=10); SUB = Font(name=F, italic=True, size=9, color="595959")
HDR = Font(name=F, bold=True, color="FFFFFF", size=10); HDRFILL = PatternFill("solid", fgColor="1F3864")
SECFILL = PatternFill("solid", fgColor="D9E1F2"); YELLOW = PatternFill("solid", fgColor="FFFF00")


def header(ws, r, cols):
    for i, h in enumerate(cols):
        c = ws.cell(row=r, column=1 + i, value=h); c.font = HDR; c.fill = HDRFILL


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(ROOT / "model" / "GRG_model_v0.5.xlsx"))
    ap.add_argument("--out", default=str(ROOT / "model" / "GRG_model_v0.6.xlsx"))
    a = ap.parse_args()
    wb = load_workbook(a.src)
    if "Simulation" in wb.sheetnames:
        del wb["Simulation"]
    ws = wb.create_sheet("Simulation", wb.sheetnames.index("Checks"))
    ws["A1"] = "Monte Carlo simulation – 10,000 runs of the full three-statement model"; ws["A1"].font = TITLE
    ws["A2"] = ("Generated by simulation/monte_carlo.py (seed 42) from the Drivers tab ranges. Values, not live formulas: "
                "re-run the script after changing assumptions. Controls: the Python base case equals this workbook's "
                "base case to £0.0m, and the balance sheet balances in all 30,000 run-years.")
    ws["A2"].font = SUB
    r = 4
    ws.cell(row=r, column=1, value="Percentiles (£m)").font = BOLD
    r += 1
    header(ws, r, ["Measure", "Year", "P5", "P25", "Median", "P75", "P95", "Mean", "Base case"])
    for row in list(csv.reader(open(RES / "summary_percentiles.csv")))[1:]:
        r += 1
        for i, v in enumerate(row):
            c = ws.cell(row=r, column=1 + i, value=float(v) if i >= 2 else v); c.font = BLACK
            if i >= 2:
                c.number_format = '#,##0.0'
    r += 2
    ws.cell(row=r, column=1, value="Probabilities").font = BOLD
    r += 1
    header(ws, r, ["Question", "", "", "", "", "", "Probability"])
    for q, p in list(csv.reader(open(RES / "probabilities.csv")))[1:]:
        r += 1
        ws.cell(row=r, column=1, value=q).font = BLACK
        c = ws.cell(row=r, column=7, value=float(p)); c.font = BLACK; c.number_format = '0.0%'
    r += 2
    ws.cell(row=r, column=1, value="Tornado: FY28 underlying PBT with one driver at its min / max (others at base)").font = BOLD
    r += 1
    header(ws, r, ["Driver", "", "", "At min", "At max", "Swing", "Lowest cash at min", "Lowest cash at max"])
    for row in list(csv.reader(open(RES / "tornado_fy28_upbt.csv")))[1:]:
        r += 1
        ws.cell(row=r, column=1, value=row[0]).font = BLACK
        for i, v in enumerate(row[1:]):
            c = ws.cell(row=r, column=4 + i, value=float(v)); c.font = BLACK; c.number_format = '#,##0.0'
    r += 2
    ws.cell(row=r, column=1, value="Your conclusions (Session E, in your own words)").font = BOLD
    for k in range(3):
        ws.cell(row=r + 1 + k, column=1, value=f"{k + 1}.").font = BLACK
        ws.cell(row=r + 1 + k, column=2).fill = YELLOW
    ws.column_dimensions["A"].width = 58
    for col in "BCDEFGHI":
        ws.column_dimensions[col].width = 12
    img1 = Image(str(RES / "fy26_upbt_histogram.png")); img1.width, img1.height = 640, 336
    img2 = Image(str(RES / "tornado_fy28_upbt.png")); img2.width, img2.height = 640, 304
    ws.add_image(img1, "K4"); ws.add_image(img2, "K23")
    ws.sheet_view.showGridLines = False
    wb.save(a.out)
    print("saved", a.out)


if __name__ == "__main__":
    main()
